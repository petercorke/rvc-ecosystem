#!/usr/bin/env python
"""Regenerate the bootstrap cell in every notebook from the repo's template.

Google Colab fetches only the single .ipynb file it is opened from and cannot see its
neighbours, so each notebook carries its own copy of the code that installs the package.
That copy is a generated cell whose first line is ``# <NICKNAME>_BOOTSTRAP_CELL``; the
source of truth is ``_<nickname>_nb_bootstrap.py`` in the notebooks folder, which in turn
starts from ``bootstrap_template.py`` in this repo.  See ``notebooks.md`` section 3.

What a notebook needs beyond the default is in its own metadata, under
``<nickname>_bootstrap``, for example ``{"extras": ["ik"], "min_version": "1.5.0"}``.
Each key becomes an argument of ``ensure_installed`` in the generated cell, so it must be
one that the template's ``ensure_installed`` takes: a misspelling is an error here, not a
notebook that fails to install on Colab.

Usage::

    sync_bootstrap.py            regenerate the cells that are out of date
    sync_bootstrap.py --check    only report; exit 1 if any is out of date
    sync_bootstrap.py --add      also add the cell to a notebook that lacks it

The repo's nickname is read from the name of the template in the folder,
``_<nickname>_nb_bootstrap.py``; ``--nickname`` chooses between several.
"""

from __future__ import annotations

import argparse
import ast
import json
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import nbconfig

# Folds the cell's code by default (VS Code and JupyterLab both honour this): a reader
# sees the one-line header and the status line the cell prints, not the boilerplate.
FOLDED_METADATA = {"jupyter": {"source_hidden": True}}


def compact(template: str) -> str:
    """The template's code without its docstrings and comments.

    A notebook shows its bootstrap cell, and a short one is less daunting than the
    documented source, which stays in the template.
    """
    tree = ast.parse(template)
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                node.body = body[1:] or [ast.Pass()]
    return ast.unparse(tree)


def parameters(template: str) -> list[str]:
    """The names of the arguments of ``ensure_installed`` in the template."""
    for node in ast.walk(ast.parse(template)):
        if isinstance(node, ast.AsyncFunctionDef) and node.name == "ensure_installed":
            args = node.args
            return [a.arg for a in args.posonlyargs + args.args + args.kwonlyargs]
    raise ValueError("the template has no 'async def ensure_installed'")


def call(template: str, settings: dict) -> str:
    """The call of ``ensure_installed`` for a notebook's settings.

    :raises ValueError: for a setting that ``ensure_installed`` does not take
    """
    known = parameters(template)
    unknown = sorted(set(settings) - set(known))
    if unknown:
        raise ValueError(
            f"ensure_installed does not take {', '.join(unknown)}; it takes {', '.join(known)}"
        )
    arguments = [f"{k}={settings[k]!r}" for k in known if k in settings]
    return f"ensure_installed({', '.join(arguments)})"


def generated_source(
    config: nbconfig.Config, template: str, settings: dict
) -> list[str]:
    """The full source, as nbformat lines, of the bootstrap cell."""
    header = (
        f"{config.marker}: installs the package (Colab, JupyterLite or local), generated by "
        f"sync_bootstrap.py from {config.template_path.name}, do not edit\n"
    )
    body = (
        f"{header}\n{compact(template)}\n\nCOLAB = await {call(template, settings)}\n"
    )
    return body.splitlines(keepends=True)


def settings_of(nb: dict, config: nbconfig.Config) -> dict:
    return dict(nb.get("metadata", {}).get(config.metadata_key, {}))


def ensure_cell_ids(nb: dict) -> bool:
    """Give every cell an ``id``, as nbformat 4.5 requires.

    VS Code adds ids to a notebook that lacks them as soon as it is opened, which shows as
    a change to the file, so they are committed instead.

    :returns: True if any id was added.
    """
    cells = nb.get("cells", [])
    used = {c["id"] for c in cells if "id" in c}
    changed = False
    for cell in cells:
        if "id" not in cell:
            new = uuid.uuid4().hex[:8]
            while new in used:
                new = uuid.uuid4().hex[:8]
            cell["id"] = new
            used.add(new)
            changed = True
    if changed and nb.get("nbformat_minor", 0) < 5:
        nb["nbformat_minor"] = 5
    return changed


def source_text(cell: dict) -> str:
    source = cell.get("source", [])
    return "".join(source) if isinstance(source, list) else source


def is_bootstrap_cell(cell: dict, config: nbconfig.Config) -> bool:
    if cell.get("cell_type") != "code":
        return False
    text = source_text(cell)
    first = text.splitlines()[0].strip() if text.strip() else ""
    return first.startswith(config.marker)


def new_cell(source: list[str]) -> dict:
    return {
        "cell_type": "code",
        "execution_count": None,
        "id": uuid.uuid4().hex[:8],
        "metadata": {"jupyter": dict(FOLDED_METADATA["jupyter"])},
        "outputs": [],
        "source": source,
    }


def process_notebook(
    path: Path, config: nbconfig.Config, template: str, fix: bool, add: bool = False
) -> bool:
    """Check (and optionally fix) one notebook's bootstrap cell and cell ids.

    :returns: True if the notebook was (or would be) changed.
    """
    raw = path.read_text(encoding="utf-8")
    nb = json.loads(raw)

    changed = (
        ensure_cell_ids(nb) if fix else any("id" not in c for c in nb.get("cells", []))
    )
    desired = generated_source(config, template, settings_of(nb, config))
    cells = nb.get("cells", [])
    found = False
    for cell in cells:
        if not is_bootstrap_cell(cell, config):
            continue
        found = True
        current = cell.get("source", [])
        current = current if isinstance(current, list) else [current]
        if (
            current != desired
            or cell.get("metadata", {}).get("jupyter") != FOLDED_METADATA["jupyter"]
        ):
            changed = True
            if fix:
                cell["source"] = desired
                cell.setdefault("metadata", {})["jupyter"] = dict(
                    FOLDED_METADATA["jupyter"]
                )
        break
    if not found and add:
        changed = True
        if fix:
            # after the title cell if the notebook starts with prose
            index = 1 if cells and cells[0].get("cell_type") == "markdown" else 0
            cells.insert(index, new_cell(desired))
            ensure_cell_ids(nb)

    if changed and fix:
        nbconfig.write(path, nbconfig.canonical_text(nb))
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    nbconfig.add_arguments(parser)
    parser.add_argument(
        "--check", action="store_true", help="report only; exit 1 if any is out of date"
    )
    parser.add_argument(
        "--add", action="store_true", help="add the cell to a notebook that lacks it"
    )
    args = parser.parse_args(argv)
    config = nbconfig.config_from(args)

    try:
        template_path = config.template_path
    except nbconfig.ConfigError as err:
        print(err, file=sys.stderr)
        return 2
    if not template_path.exists():
        print(f"{template_path}: no such template", file=sys.stderr)
        return 2
    template = template_path.read_text(encoding="utf-8")

    any_changed = False
    for path in nbconfig.notebooks(config, args.files):
        try:
            changed = process_notebook(
                path, config, template, fix=not args.check, add=args.add
            )
        except ValueError as err:
            print(f"{path}: {err}", file=sys.stderr)
            return 2
        if changed:
            any_changed = True
            print(
                f"{path}: bootstrap cell or cell ids {'out of date' if args.check else 'regenerated'}"
            )
    return 1 if args.check and any_changed else 0


if __name__ == "__main__":
    sys.exit(main())
